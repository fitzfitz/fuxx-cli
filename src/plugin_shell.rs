//! `plugins.zsh`: the zsh script fuxx's terminals source after your `.zshrc`, built from the
//! enabled helper plugins. Pure text, plus one atomic write beside the shell integration.

use std::fs;
use std::io::{self, Write};
use std::os::unix::fs::{OpenOptionsExt, PermissionsExt};
use std::path::Path;
use std::sync::Mutex;

use crate::plugin_store::{Folders, Record};

const HEADER: &str = "# fuxx plugins (generated by fuxx; edits are replaced)\n";

/// `s` as one zsh word in single quotes, so spaces and `$` mean nothing.
pub fn zsh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', "'\\''"))
}

/// The script: for each enabled helper, in order, its `bin` on `$path` and its `zsh` scripts
/// sourced with `FUXX_PLUGIN_DIR` and `FUXX_PLUGIN_DATA` set only meanwhile.
pub fn script(f: &Folders, records: &[Record]) -> String {
    let q = |p: &Path| zsh_quote(&p.display().to_string());
    let mut out = HEADER.to_string();
    for r in records.iter().filter(|r| r.enabled) {
        let dir = f.plugin(&r.id);
        if let Some(bin) = &r.bin {
            out.push_str(&format!("path=({} $path)\n", q(&dir.join(bin))));
        }
        if r.zsh.is_empty() {
            continue;
        }
        // An error in one plugin's scripts must not stop the next plugin or the unset, so the
        // block has an `always` part, and clearing TRY_BLOCK_ERROR there lets zsh carry on.
        out.push_str("{\n");
        out.push_str(&format!(
            "export FUXX_PLUGIN_DIR={} FUXX_PLUGIN_DATA={}\n",
            q(&dir),
            q(&f.data_of(&r.id))
        ));
        for file in &r.zsh {
            out.push_str(&format!("builtin source -- {}\n", q(&dir.join(file))));
        }
        out.push_str("} always {\nTRY_BLOCK_ERROR=0\nunset FUXX_PLUGIN_DIR FUXX_PLUGIN_DATA\n}\n");
    }
    out
}

/// True when any enabled plugin runs code, so terminals need the script at all.
pub fn any_enabled(records: &[Record]) -> bool {
    records.iter().any(|r| r.enabled && r.runs_code())
}

/// Two writes in one process share a temp name, so they take turns.
static WRITE: Mutex<()> = Mutex::new(());

/// Write the script to `<dir>/zsh/plugins.zsh` (temp file, then rename; `0o644`).
pub fn write(dir: &Path, f: &Folders, records: &[Record]) -> io::Result<()> {
    let _turn = WRITE.lock().unwrap_or_else(|e| e.into_inner());
    let zsh = dir.join("zsh");
    fs::create_dir_all(&zsh)?;
    let path = zsh.join("plugins.zsh");
    let tmp = zsh.join(format!("plugins.zsh.{}.tmp", std::process::id()));
    let written = write_file(&tmp, &script(f, records)).and_then(|()| fs::rename(&tmp, &path));
    if written.is_err() {
        let _ = fs::remove_file(&tmp);
    }
    written
}

/// `text` as a new file at `path`, `0o644` whatever the umask.
fn write_file(path: &Path, text: &str) -> io::Result<()> {
    let mut file = fs::OpenOptions::new()
        .write(true)
        .create(true)
        .truncate(true)
        .mode(0o644)
        .open(path)?;
    file.write_all(text.as_bytes())?;
    file.set_permissions(fs::Permissions::from_mode(0o644))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::plugin_source::Installed;

    fn rec(id: &str, enabled: bool, bin: Option<&str>, zsh: &[&str]) -> Record {
        Record {
            id: id.into(),
            name: id.into(),
            version: "1".into(),
            description: None,
            repo: "o/r".into(),
            installed: Installed::Tag("v1".into()),
            themes: Vec::new(),
            installed_at: 0,
            enabled,
            bin: bin.map(String::from),
            zsh: zsh.iter().map(|s| s.to_string()).collect(),
        }
    }

    fn folders() -> Folders {
        Folders {
            plugins: "/p".into(),
            data: "/d".into(),
        }
    }

    #[test]
    fn script_is_empty_with_no_helpers() {
        assert_eq!(
            script(&folders(), &[]),
            "# fuxx plugins (generated by fuxx; edits are replaced)\n"
        );
    }

    #[test]
    fn script_loads_enabled_helpers_in_order() {
        let records = [
            rec("off", false, Some("bin"), &["a.zsh"]),
            rec("theme", true, None, &[]),
            rec("on", true, Some("bin"), &["shell/a.zsh"]),
        ];
        assert!(any_enabled(&records));
        assert_eq!(
            script(&folders(), &records),
            "# fuxx plugins (generated by fuxx; edits are replaced)\n\
             path=('/p/on/bin' $path)\n\
             {\n\
             export FUXX_PLUGIN_DIR='/p/on' FUXX_PLUGIN_DATA='/d/on'\n\
             builtin source -- '/p/on/shell/a.zsh'\n\
             } always {\n\
             TRY_BLOCK_ERROR=0\n\
             unset FUXX_PLUGIN_DIR FUXX_PLUGIN_DATA\n\
             }\n"
        );
        assert!(!any_enabled(&records[..2]));
    }

    #[test]
    fn paths_with_spaces_and_quotes_are_quoted() {
        assert_eq!(zsh_quote("/a b/it's"), r"'/a b/it'\''s'");
    }

    #[test]
    fn write_is_atomic_and_0644() {
        let dir = std::env::temp_dir().join(format!("fuxx-ps-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        let records = [rec("on", true, Some("bin"), &[])];
        write(&dir, &folders(), &records).unwrap();
        let file = dir.join("zsh/plugins.zsh");
        assert_eq!(
            fs::read_to_string(&file).unwrap(),
            script(&folders(), &records)
        );
        assert_eq!(
            fs::metadata(&file).unwrap().permissions().mode() & 0o777,
            0o644
        );
        let left: Vec<_> = fs::read_dir(dir.join("zsh"))
            .unwrap()
            .map(|e| e.unwrap().file_name())
            .collect();
        assert_eq!(left, vec![std::ffi::OsString::from("plugins.zsh")]);
        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn a_broken_plugin_does_not_stop_the_next() {
        use crate::shell_integration::test_zsh::{run, screen_text, spawn};
        let root = std::env::temp_dir().join(format!("fuxx-ps-broken-{}", std::process::id()));
        let _ = fs::remove_dir_all(&root);
        let (plugins, data, si, home) = (
            root.join("plugins"),
            root.join("data"),
            root.join("si"),
            root.join("home"),
        );
        for (id, text) in [
            ("bad", "${undefined_fuxx_var?boom}\nP1=after\n"),
            ("good", "P2=two\n"),
        ] {
            fs::create_dir_all(plugins.join(id)).unwrap();
            fs::write(plugins.join(id).join("a.zsh"), text).unwrap();
        }
        fs::create_dir_all(&home).unwrap();
        let f = Folders { plugins, data };
        let records = [
            rec("bad", true, None, &["a.zsh"]),
            rec("good", true, None, &["a.zsh"]),
        ];
        crate::shell_integration::install(&si).unwrap();
        write(&si, &f, &records).unwrap();
        let (core, _rx) = spawn(&home, None, &si, true, true);
        run(&core, "print -r -- \"[$P2][${FUXX_PLUGIN_DIR-unset}]\"");
        let screen = screen_text(&core);
        assert!(screen.contains("[two][unset]"), "screen:\n{screen}");
        let _ = fs::remove_dir_all(&root);
    }
}
